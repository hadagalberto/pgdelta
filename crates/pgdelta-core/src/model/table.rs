//! Tables, columns, generated columns and identity columns.

use super::constraint::Constraint;
use serde::Serialize;

/// A table.
#[derive(Debug, Clone, PartialEq, Eq, Serialize)]
pub struct Table {
    /// Schema the table lives in.
    pub schema: String,
    /// Table name.
    pub name: String,
    /// Columns in physical (declaration) order.
    ///
    /// The order mirrors PostgreSQL's `attnum` order: `CREATE TABLE` keeps
    /// declaration order and `ALTER TABLE ... ADD COLUMN` appends at the
    /// end. Note that the *diff* compares columns by name only — PostgreSQL
    /// cannot reorder columns without a destructive rewrite, so pgdelta
    /// never generates reordering statements and a by-name comparison is
    /// the honest contract.
    pub columns: Vec<Column>,
    /// Constraints, keyed by name (every PostgreSQL constraint has one;
    /// unnamed constraints receive PostgreSQL's auto-generated names, see
    /// `naming.rs`).
    pub constraints: Vec<Constraint>,
}

impl Table {
    /// Looks up a column by name.
    #[must_use]
    pub fn column(&self, name: &str) -> Option<&Column> {
        self.columns.iter().find(|c| c.name == name)
    }

    /// Looks up a constraint by name.
    #[must_use]
    pub fn constraint(&self, name: &str) -> Option<&Constraint> {
        self.constraints.iter().find(|c| c.name == name)
    }

    /// Returns the column names of the table's primary key, if it has one.
    #[must_use]
    pub fn primary_key_columns(&self) -> Option<&[String]> {
        self.constraints.iter().find_map(|c| match &c.kind {
            super::ConstraintKind::PrimaryKey { columns } => Some(columns.as_slice()),
            _ => None,
        })
    }
}

/// A column.
#[derive(Debug, Clone, PartialEq, Eq, Serialize)]
pub struct Column {
    /// Column name (folded per PostgreSQL rules).
    pub name: String,
    /// Canonical data type string (see `sql/datatype.rs` for the
    /// normalisation rules).
    pub data_type: String,
    /// `NOT NULL` flag.
    pub not_null: bool,
    /// Normalised default expression, if any.
    pub default: Option<String>,
    /// Stored generated column expression, if any.
    pub generated: Option<Generated>,
    /// Identity specification, if the column is an identity column.
    ///
    /// The sequence options are always fully normalised: unspecified options
    /// take PostgreSQL's defaults exactly as documented for `CREATE
    /// SEQUENCE` (increment 1; ascending sequences default `MINVALUE` to 1,
    /// `MAXVALUE` to the data type's maximum and `START` to the minvalue;
    /// cache 1; `NO CYCLE`), so two sources that spell the defaults
    /// differently produce equal models.
    pub identity: Option<Identity>,
    /// Explicit collation, if any (a `COLLATE` clause was given).
    ///
    /// `None` means "the data type's default collation", which is how
    /// PostgreSQL stores the common case.
    pub collation: Option<String>,
}

/// A stored generated column.
///
/// Only `STORED` generated columns are modelled in milestone 1: virtual
/// generated columns are new in PostgreSQL 18 and pgdelta's generated SQL
/// targets PostgreSQL 13–18, so sources must spell `STORED` explicitly
/// (PostgreSQL 13–17 require the keyword anyway; see `docs/parser.md`).
#[derive(Debug, Clone, PartialEq, Eq, Serialize)]
pub struct Generated {
    /// Normalised generation expression.
    pub expr: String,
}

/// An identity column specification.
#[derive(Debug, Clone, PartialEq, Eq, Serialize)]
pub struct Identity {
    /// Whether inserts must specify `OVERRIDING SYSTEM VALUE` to write
    /// explicit values (`ALWAYS`) or take user values by default
    /// (`BY DEFAULT`).
    pub kind: IdentityKind,
    /// Fully-normalised sequence parameters.
    pub options: SequenceOptions,
}

/// Identity generation kinds.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize)]
pub enum IdentityKind {
    /// `GENERATED ALWAYS AS IDENTITY`.
    Always,
    /// `GENERATED BY DEFAULT AS IDENTITY`.
    ByDefault,
}

/// Fully-normalised sequence options for an identity column.
///
/// Every field is concrete: parsing fills unspecified options with the
/// PostgreSQL defaults (per the `CREATE SEQUENCE` documentation referenced
/// from `CREATE TABLE`'s `sequence_options`), and `ALTER TABLE` with `SET`
/// (`sequence_option`) statements overwrite the concrete value, exactly as
/// PostgreSQL does.
#[derive(Debug, Clone, PartialEq, Eq, Serialize)]
pub struct SequenceOptions {
    /// `INCREMENT BY` value.
    pub increment: i64,
    /// `MINVALUE`.
    pub minvalue: i64,
    /// `MAXVALUE`.
    pub maxvalue: i64,
    /// `START WITH` value.
    pub start: i64,
    /// `CACHE`.
    pub cache: i64,
    /// Whether the sequence cycles (`CYCLE`).
    pub cycle: bool,
}

/// Maximum value of the sequence's arithmetic type, given the identity
/// column's data type. PostgreSQL restricts identity columns to
/// `smallint`, `integer` and `bigint` (`CREATE TABLE`, `GENERATED ...
/// AS IDENTITY`), and the sequence defaults derive from that type.
pub(crate) fn sequence_type_range(data_type: &str) -> Option<(i64, i64)> {
    match data_type {
        "smallint" => Some((i64::from(i16::MIN), i64::from(i16::MAX))),
        "integer" => Some((i64::from(i32::MIN), i64::from(i32::MAX))),
        "bigint" => Some((i64::MIN, i64::MAX)),
        _ => None,
    }
}
